const supplement = resolveSupplement();

/** The Go tree, read from the committed list. Absent only before the transfer feature existed. */
function goComponents() {
  if (!existsSync(GO_MODULES)) {
    return [];
  }
  const { modules } = JSON.parse(readFileSync(GO_MODULES, 'utf8'));
  return modules.map((m) => {
    if (!m.copyright || !m.spdx) {
      fail(
        `go module "${m.name}" has no ${m.copyright ? 'licence' : 'copyright line'}.\n` +
          '  Re-run `npm run attributions:go` and resolve it there - do not drop the entry.',
      );
    }
    return {
      name: m.name,
      version: m.version,
      spdx: m.spdx,
      copyright: m.copyright,
    };
  });
}
const goModules = goComponents();
const index = indexInstalled();
const packages = shippedPackages();
const { resolved, unresolvedLicence, unresolvedCopyright } = resolveNpm(packages, index);

if (unresolvedLicence.length || unresolvedCopyright.length) {
  const lines = [];
  if (unresolvedLicence.length) {
    lines.push(
      `  ${unresolvedLicence.length} package(s) with no resolvable licence:`,
      ...unresolvedLicence.map((p) => `    ${p}`),
    );
  }
  if (unresolvedCopyright.length) {
    lines.push(
      `  ${unresolvedCopyright.length} package(s) with no resolvable copyright line:`,
      ...unresolvedCopyright.map((p) => `    ${p}`),
    );
  }
  fail(
    'unresolved components - refusing to emit a list that looks complete but is not.\n\n' +
      lines.join('\n') +
      '\n\n  Resolve each by adding a reviewed entry to OVERRIDES in this script, recording the\n' +
      '  evidence in its `why`. Never drop a component to make this pass.',
  );
}

const byLicence = new Map();
// The Go tree joins the npm packages in the SAME groups: a reader asking "what MIT code is in this
// app" wants one answer, not one per build system.
for (const pkg of [...resolved, ...goModules]) {
  if (!byLicence.has(pkg.spdx)) {
    byLicence.set(pkg.spdx, []);
  }
  byLicence.get(pkg.spdx).push({
    name: pkg.name,
    version: pkg.version,
    copyright: pkg.copyright,
  });
}

const groups = [...byLicence.entries()]
  .map(([spdx, components]) => ({
    spdx,
    count: components.length,
    components: components.sort((a, b) => byCodepoint(a.name, b.name)),
  }))
  .sort((a, b) => b.count - a.count || byCodepoint(a.spdx, b.spdx));

const spdxIds = [
  ...new Set([...groups.map((g) => g.spdx), ...supplement.map((b) => b.spdx)]),
].sort();
const texts = licenceBodies(spdxIds);

const total = resolved.length + goModules.length + supplement.length;
const output = emit({ bundled: supplement, groups, texts, total });
const sizeKb = (Buffer.byteLength(output) / 1024).toFixed(1);
const summary =
  `${total} distributed components (${resolved.length} npm + ${goModules.length} go + ` +
    `${supplement.length} bundled), ` +
  `${groups.length} licence groups, ${sizeKb} KB`;

if (process.argv.includes('--check')) {
  // The drift gate. A dependency added, removed or bumped without regenerating leaves the Licence
  // screen quietly wrong, which is the failure mode that produced the gap this feature closes.
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (current === null) {
    fail(`${OUT} does not exist. Run \`npm run attributions\`.`);
  }
  if (current !== output) {
    const before = current.split('\n');
    const after = output.split('\n');
    const at = before.findIndex((line, i) => line !== after[i]);
    fail(
      `${OUT} is out of date - the dependency tree has changed since it was generated.\n\n` +
        `  checked in : ${before.length} lines\n` +
        `  regenerated: ${after.length} lines\n` +
        `  first difference at line ${at + 1}:\n` +
        `    -  ${(before[at] ?? '(missing)').slice(0, 160)}\n` +
        `    +  ${(after[at] ?? '(missing)').slice(0, 160)}\n\n` +
        '  Run `npm run attributions` (and `npm run attributions:scan` first if dependencies\n' +
        '  changed) and commit the result.',
    );
  }
  console.log(`gen-attributions: up to date - ${summary}`);
  process.exit(0);
}

writeFileSync(OUT, output);
console.log(`gen-attributions: ${summary}`);

const BUDGET_KB = 80;
if (Number(sizeKb) > BUDGET_KB) {
  fail(
    `the generated module is ${sizeKb} KB, over the ${BUDGET_KB} KB budget.\n` +
      '  Licence bodies are already deduped per identifier; revisit the budget deliberately\n' +
      '  rather than trimming components.',
  );
}
