// Third-party attribution generator (dev-time only).
//
// Emits src/content/attributions.generated.ts - the data the in-app Licence screen renders. Run with
// `npm run attributions`; `npm run attributions:check` regenerates to a temp file and fails if the
// checked-in module has drifted, which is what keeps the list from silently rotting.
//
// Why this is bespoke rather than `license-checker`: the components with the STRICTEST notice
// requirements are not npm packages at all. SQLCipher is vendored C source inside op-sqlite and its
// licence explicitly requires reproducing the notice in binary distributions; OpenSSL is a native
// prefab dependency; both bundled typefaces are OFL-1.1 files under assets/fonts. A tree-walker sees
// none of them, so it would produce a list that looks complete and is not - the exact failure this
// whole feature exists to fix. Everything unresolvable is therefore a HARD ERROR here, never a warning.
//
// Shape (matches what the design's screens read):
//   bundled[]  { name, version, spdx, kindCs, kindEn, copyright }   the non-npm components
//   groups[]   { spdx, count, components[ { name, version, copyright } ] }
//   texts      { [spdx]: licence body, copyright lines stripped - those live per component }
//
// The licence BODIES are checked in under assets/licenses/. They are deliberately not scraped from a
// representative package at generation time: whichever package happened to be representative would
// change between installs and the drift check would thrash.

