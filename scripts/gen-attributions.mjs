// Dual-licensed packages: we elect the permissive option and record that we did.
const DUAL_ELECTION = {
  '(MIT OR Apache-2.0)': 'MIT',
  '(MIT OR CC0-1.0)': 'MIT',
  '(MIT OR WTFPL)': 'MIT',
};

/**
 * Codepoint order - NEVER `localeCompare`, which is locale-sensitive and made this generator emit a
 * different file on different machines. Node picks its collation up from the environment, and Czech
 * (this project's home locale) treats "ch" as a single letter sorting after "h": on a cs-CZ machine
 * `@tamagui/checkbox` sorted 27 places away from where CI's C locale put it. Same components, same
 * count, different order - so the drift gate failed on CI for commits that passed locally, which is
 * exactly the false alarm that teaches people to ignore a compliance check.
 */
const byCodepoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const fail = (msg) => {
  console.error(`\n  gen-attributions: ${msg}\n`);
  process.exit(1);
};

// --- what actually ships ----------------------------------------------------
// NOT `npm ls --prod`. That lists 717 packages, including metro, typescript and react-devtools-core -
// dev-machine tooling that react-native depends on but which never reaches a device. Claiming those as
// distributed components would be simply false (and is the error the design's placeholder data made).
//
// The honest source is the release bundle itself: Metro's source map names every module it actually
// included. That is 170 packages. `--scan` rebuilds the list; the routine path reads it back.
const MODULE_LIST = 'scripts/bundled-modules.json';

function dependencyFingerprint() {
  const json = JSON.parse(readFileSync('package.json', 'utf8'));
  return JSON.stringify(json.dependencies ?? {});
}

function scanBundle() {
  const platforms = ['android', 'ios'];
  const modules = new Set();
  for (const platform of platforms) {
    const map = `/tmp/attributions-${platform}.map`;
    console.log(`gen-attributions: bundling ${platform}…`);
    execFileSync(
      'npx',
      [
        'react-native', 'bundle',
        '--platform', platform,
        '--dev', 'false',
        '--entry-file', 'index.js',
        '--bundle-output', `/tmp/attributions-${platform}.jsbundle`,
        '--sourcemap-output', map,
      ],
      { stdio: ['ignore', 'ignore', 'inherit'], maxBuffer: 64 * 1024 * 1024 },
    );
    for (const source of JSON.parse(readFileSync(map, 'utf8')).sources ?? []) {
      // Take the LAST node_modules segment so a nested copy is credited to its own package.
      const normalised = source.replace(/\\/g, '/');
      const segments = normalised.split('node_modules/');
      if (segments.length < 2) {
        continue;
      }
      const match = /^((?:@[^/]+\/)?[^/]+)/.exec(segments[segments.length - 1]);
      if (!match) {
        continue;
      }
      // Record the DIRECTORY, not just the name. npm installs several of these packages at more than
      // one version at once (a hoisted root copy plus a nested one - react-is, color-convert,
      // escape-string-regexp, color-name, is-arrayish), and a bare name cannot say which copy Metro
      // actually bundled. Generation used to guess by taking the first filesystem match, whose order
      // differs between a developer's accumulated node_modules and CI's fresh `npm ci` - so the two
      // produced different version strings for the same commit and `--check` failed on CI only.
      // The path is the one unambiguous answer, and it is right here at scan time.
      const cut = normalised.lastIndexOf('node_modules/') + 'node_modules/'.length;
      modules.add(
        path.relative(process.cwd(), normalised.slice(0, cut) + match[1]),
      );
    }
  }
  writeFileSync(
    MODULE_LIST,
    `${JSON.stringify(
      {
        _comment:
          'GENERATED by `npm run attributions:scan`. Every npm package DIRECTORY Metro puts in the ' +
          'release bundle for either platform - i.e. what actually ships. Paths, not bare names, so ' +
          'a package installed at two versions resolves to the copy that was really bundled. ' +
          'Regenerate when dependencies change.',
        dependencyFingerprint: dependencyFingerprint(),
        platforms,
        modules: [...modules].sort(),
      },
      null,
      2,
    )}\n`,
  );
  console.log(`gen-attributions: ${modules.size} packages ship (scanned ${platforms.join(' + ')})`);
}

function shippedPackages() {
  if (!existsSync(MODULE_LIST)) {
    fail(`${MODULE_LIST} is missing. Run \`npm run attributions:scan\` to build it.`);
  }
  const list = JSON.parse(readFileSync(MODULE_LIST, 'utf8'));
  if (list.dependencyFingerprint !== dependencyFingerprint()) {
    fail(
      'dependencies changed since the bundle was last scanned, so the shipped-module list is stale.\n' +
        '  Run `npm run attributions:scan` to rebuild it, then regenerate.',
    );
  }
  // Read each bundled package's identity out of ITS OWN directory. Deterministic by construction -
  // the directory came from the bundle's source map, so there is nothing left to guess. This used to
  // take the first filesystem match for a bare name, which picked a different copy on CI than
  // locally whenever npm had installed a package at two versions, and `--check` then failed on CI
  // for a commit that passed on the developer's machine.
  const packages = [];
  const missing = [];
  for (const dir of list.modules) {
    const manifest = path.join(dir, 'package.json');
    if (!existsSync(manifest)) {
      missing.push(dir);
      continue;
    }
    const json = JSON.parse(readFileSync(manifest, 'utf8'));
    packages.push({ name: json.name, version: json.version, dir });
  }
  if (missing.length) {
    fail(
      `${missing.length} bundled package(s) are not installed: ${missing.join(', ')}.\n` +
        '  Run `npm ci`, then rescan.',
    );
  }
  // A package bundled at two versions legitimately appears twice - both copies are distributed, so
  // both notices are owed. Sort so the emitted file is stable regardless of scan order.
  packages.sort((a, b) =>
    a.name === b.name
      ? byCodepoint(a.version, b.version)
      : byCodepoint(a.name, b.name),
  );
  return packages;
}

// --- where each package actually lives -------------------------------------
// npm hoists, and `npm ls` does not report paths, so nested copies (node_modules/a/node_modules/b)
// would otherwise resolve to nothing. Index the filesystem once and look packages up by name@version.
function indexInstalled() {
  const index = new Map();
  const visit = (dir) => {
    let entries;
    try {
      entries = readdirSync(dir);
    } catch {
      return;
    }
    for (const entry of entries) {
      if (entry === '.bin' || entry === '.cache') {
        continue;
      }
      const full = path.join(dir, entry);
      if (entry.startsWith('@')) {
        visit(full);
        continue;
      }
      const manifest = path.join(full, 'package.json');
      if (existsSync(manifest)) {
        try {
          const json = JSON.parse(readFileSync(manifest, 'utf8'));
          if (json.name && json.version) {
            const key = `${json.name}@${json.version}`;
            if (!index.has(key)) {
              index.set(key, full);
            }
          }
        } catch {
          /* an unreadable manifest is not ours to fix; the caller fails on the miss */
        }
      }
      const nested = path.join(full, 'node_modules');
      if (existsSync(nested) && statSync(nested).isDirectory()) {
        visit(nested);
      }
    }
  };
  visit('node_modules');
  return index;
}

const LICENSE_FILE = /^(LICENSE|LICENCE|COPYING)/i;

function licenceFileIn(dir) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return null;
  }
  const match = entries.find((e) => LICENSE_FILE.test(e));
  return match ? path.join(dir, match) : null;
}

const COPYRIGHT_LINE = /^[ \t]*(Copyright[ \t].+)$/im;

function copyrightFrom(file) {
  if (!file || !existsSync(file)) {
    return null;
  }
  const match = COPYRIGHT_LINE.exec(readFileSync(file, 'utf8'));
  return match ? match[1].trim().replace(/\s+/g, ' ') : null;
}

function overrideFor(name) {
  if (OVERRIDES[name]) {
    return OVERRIDES[name];
  }
  const scope = name.startsWith('@') ? `${name.split('/')[0]}/*` : null;
  return scope && OVERRIDES[scope] ? OVERRIDES[scope] : null;
}

function declaredLicence(json) {
  let value = json.license ?? json.licenses;
  if (Array.isArray(value)) {
    value = value[0];
  }
  if (value && typeof value === 'object') {
    value = value.type;
  }
  if (typeof value !== 'string' || !value.trim()) {
    return null;
  }
  const spdx = value.trim();
  return DUAL_ELECTION[spdx] ?? spdx;
}

function resolveNpm(packages, index) {
  const resolved = [];
  const unresolvedLicence = [];
  const unresolvedCopyright = [];

  for (const pkg of packages) {
    // `pkg.dir` is the copy the bundle actually pulled in; the index is only a fallback for entries
    // that predate the path-based module list.
    const dir = pkg.dir ?? index.get(`${pkg.name}@${pkg.version}`);
    const override = overrideFor(pkg.name);
    let spdx = null;
    let copyright = null;

    if (dir) {
      const json = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
      spdx = declaredLicence(json);
      copyright = copyrightFrom(licenceFileIn(dir));
    }
    spdx = spdx ?? override?.spdx ?? null;
    copyright = copyright ?? override?.copyright ?? null;

    if (!spdx) {
      unresolvedLicence.push(`${pkg.name}@${pkg.version}${dir ? '' : ' (not installed)'}`);
      continue;
    }
    if (!copyright) {
      unresolvedCopyright.push(`${pkg.name}@${pkg.version}`);
      continue;
    }
    resolved.push({ ...pkg, spdx, copyright });
  }
  return { resolved, unresolvedLicence, unresolvedCopyright };
}

// Minimal TrueType `name`-table reader - enough to pull nameID 0 (copyright) and 5 (version), which
// are what a font states about itself. Avoids depending on a font library for two fields.
function fontNames(file) {
  const buf = readFileSync(file);
  const tableCount = buf.readUInt16BE(4);
  let nameTable = null;
  for (let i = 0; i < tableCount; i++) {
    const rec = 12 + 16 * i;
    if (buf.toString('latin1', rec, rec + 4) === 'name') {
      nameTable = { offset: buf.readUInt32BE(rec + 8), length: buf.readUInt32BE(rec + 12) };
      break;
    }
  }
  if (!nameTable) {
    return {};
  }
  const base = nameTable.offset;
  const count = buf.readUInt16BE(base + 2);
  const storage = base + buf.readUInt16BE(base + 4);
  const out = {};
  for (let i = 0; i < count; i++) {
    const rec = base + 6 + 12 * i;
    const platformId = buf.readUInt16BE(rec);
    const nameId = buf.readUInt16BE(rec + 6);
    const length = buf.readUInt16BE(rec + 8);
    const offset = buf.readUInt16BE(rec + 10);
    const slice = buf.subarray(storage + offset, storage + offset + length);
    const value = platformId === 3 ? slice.toString('utf16le').replace(/\0/g, '') : slice.toString('latin1');
    const decoded = platformId === 3 ? swapUtf16(slice) : value;
    if (out[nameId] === undefined && decoded.trim()) {
      out[nameId] = decoded.trim();
    }
  }
  return out;
}

function swapUtf16(slice) {
  const swapped = Buffer.from(slice);
  swapped.swap16();
  return swapped.toString('utf16le');
}

function matchIn(file, re, what, name) {
  if (!existsSync(file)) {
    fail(`bundled component "${name}": ${what} source ${file} does not exist`);
  }
  const match = re.exec(readFileSync(file, 'utf8'));
  if (!match) {
    fail(
      `bundled component "${name}": could not read its ${what} from ${file}.\n` +
        '  The file changed shape. Re-read it and update the pattern - do not hardcode the value.',
    );
  }
  return match[1].trim();
}

function resolveSupplement() {
  return SUPPLEMENT.map((entry) => {
    if (!existsSync(entry.assertPath)) {
      fail(
        `bundled component "${entry.name}" expects ${entry.assertPath}, which no longer exists.\n` +
          '  A dependency bump probably moved or dropped it. Re-verify the component still ships,\n' +
          '  then update SUPPLEMENT in this script - do not delete the entry to make this pass.',
      );
    }

    let { copyright, version } = entry;
    if (entry.fromFont) {
      const names = fontNames(entry.fromFont);
      copyright = names[0];
      // nameID 5 reads "Version 2.001; ttfautohint (v1.8.3)" - keep the number.
      const raw = names[5] || '';
      version = (/([0-9]+\.[0-9]+)/.exec(raw) || [])[1] || raw;
      if (!copyright || !version) {
        fail(`bundled component "${entry.name}": no copyright/version in ${entry.fromFont}`);
      }
    }
    if (entry.copyrightFrom) {
      copyright = copyrightFrom(entry.copyrightFrom);
    }
    if (entry.versionFrom) {
      version = matchIn(entry.versionFrom.file, entry.versionFrom.re, 'version', entry.name);
    }
    if (!copyright) {
      fail(`bundled component "${entry.name}" has no resolvable copyright line`);
    }
    if (!version) {
      fail(`bundled component "${entry.name}" has no resolvable version`);
    }

    return {
      name: entry.name,
      version,
      spdx: entry.spdx,
      kindCs: entry.kindCs,
      kindEn: entry.kindEn,
      copyright,
    };
  });
}

function licenceBodies(spdxIds) {
  const texts = {};
  const missing = [];
  for (const spdx of spdxIds) {
    const file = path.join(LICENSE_BODY_DIR, `${spdx}.txt`);
    if (!existsSync(file)) {
      missing.push(`${spdx}  ->  ${file}`);
      continue;
    }
    texts[spdx] = readFileSync(file, 'utf8').trimEnd();
  }
  if (missing.length) {
    fail(
      `no licence body checked in for ${missing.length} identifier(s):\n    ` +
        missing.join('\n    ') +
        '\n\n  Add the verbatim licence text at that path. Do not paraphrase or summarize it.',
    );
  }
  return texts;
}

const ts = (value) => JSON.stringify(value);

function emit({ bundled, groups, texts, total }) {
  return `// GENERATED by scripts/gen-attributions.mjs - DO NOT EDIT BY HAND.
// Run \`npm run attributions\` to regenerate; \`npm run attributions:check\` fails CI on drift.
//
// Every component distributed in the app binary, with the copyright notice its licence requires us to
// reproduce. Licence bodies are stored once per identifier (they are identical across components); the
// copyright lines are per component, because that is the part each licence actually demands.

export interface AttributionComponent {
  readonly name: string;
  readonly version: string;
  readonly copyright: string;
}

export interface AttributionGroup {
  readonly spdx: string;
  readonly count: number;
  readonly components: readonly AttributionComponent[];
}

/** A component compiled or bundled into the binary that is not an npm package. */
export interface BundledComponent extends AttributionComponent {
  readonly spdx: string;
  readonly kindCs: string;
  readonly kindEn: string;
}

/** Total distributed components - npm packages plus the bundled ones. */
export const ATTRIBUTION_TOTAL = ${total};

export const BUNDLED_COMPONENTS: readonly BundledComponent[] = ${ts(bundled)};

export const ATTRIBUTION_GROUPS: readonly AttributionGroup[] = ${ts(groups)};

/** The licence body for each identifier, verbatim, copyright lines excluded. */
export const LICENCE_TEXTS: Readonly<Record<string, string>> = ${ts(texts)};
`;
}

