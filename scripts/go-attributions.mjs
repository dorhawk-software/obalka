// Licences for the Go modules that ship inside the transfer's .aar / .xcframework (025 T020).
//
// `gen-attributions.mjs` scans a METRO BUNDLE, so it cannot see a single one of these: they are
// compiled into a native archive long before Metro runs. Without this, the app would ship a Go
// dependency tree with no attribution at all, which is exactly the failure the attribution generator
// exists to prevent - and the one it would not have noticed.
//
// The OUTPUT is committed (`scripts/go-modules.json`), so the drift check runs on a machine with no
// Go installed. Regenerate with `npm run attributions:go` after changing native/transfer.

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const MODULE_DIR = 'native/transfer';
const OUT = 'scripts/go-modules.json';

const LICENSE_NAMES = /^(LICENSE|LICENCE|COPYING)(\.(md|txt))?$/i;

/** Read the SPDX id out of a licence body. Conservative: an unknown body is a hard error. */
function spdxOf(body, modulePath) {
  const head = body.slice(0, 2000);
  if (/Apache License\s*\n?\s*Version 2\.0/i.test(head)) {
    return 'Apache-2.0';
  }
  if (/Mozilla Public License Version 2\.0/i.test(head)) {
    return 'MPL-2.0';
  }
  if (/ISC License/i.test(head)) {
    return 'ISC';
  }
  if (/Redistribution and use in source and binary forms/i.test(head)) {
    // BSD. Three clauses or two, told apart by the endorsement clause.
    return /Neither the name|names of its contributors may be used to endorse/i.test(body)
      ? 'BSD-3-Clause'
      : 'BSD-2-Clause';
  }
  if (/Permission is hereby granted, free of charge/i.test(head)) {
    return 'MIT';
  }
  // zlib/libpng. Its giveaway is the "origin must not be misrepresented" clause, which no other
  // permissive licence carries - croc reaches it through `connectproxy`.
  if (/The origin of this software must not be misrepresented/i.test(body)) {
    return 'Zlib';
  }
  throw new Error(
    `go-attributions: cannot identify the licence of ${modulePath}. ` +
      'Add it deliberately rather than letting it ship unattributed.',
  );
}

function copyrightOf(body) {
  const line = body
    .split('\n')
    .map(l => l.trim())
    .find(l => /^copyright/i.test(l) && !/^copyright\s*\(c\)\s*$/i.test(l));
  return line ? line.replace(/\s+/g, ' ') : null;
}

function modules() {
  const raw = execFileSync(
    'go',
    [
      'list',
      '-deps',
      '-f',
      '{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}',
      '.',
      // The binding's own runtime, which gomobile compiles in beside the wrapper and which nothing in
      // this package imports - so `.` alone never listed golang.org/x/mobile (found in 025 T022).
      'golang.org/x/mobile/bind/seq',
    ],
    { cwd: MODULE_DIR, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  const seen = new Map();
  for (const line of raw.split('\n')) {
    const [modPath, version, dir] = line.split('\t');
    if (!modPath || !dir) {
      continue;
    }
    // Our own module is not a third-party component.
    if (modPath === 'obalka/transfer') {
      continue;
    }
    seen.set(modPath, { path: modPath, version, dir });
  }
  return [...seen.values()].sort((a, b) => (a.path < b.path ? -1 : 1));
}

const out = [];
const unresolved = [];
for (const m of modules()) {
  const file = existsSync(m.dir)
    ? readdirSync(m.dir).find(n => LICENSE_NAMES.test(n))
    : null;
  if (!file) {
    unresolved.push(m.path);
    continue;
  }
  const body = readFileSync(path.join(m.dir, file), 'utf8');
  out.push({
    name: m.path,
    version: m.version,
    spdx: spdxOf(body, m.path),
    copyright: copyrightOf(body),
  });
}

if (unresolved.length > 0) {
  console.error(
    `\n  go-attributions: no licence file found for:\n    ${unresolved.join('\n    ')}\n\n` +
      '  Resolve each by hand rather than shipping it unattributed.\n',
  );
  process.exit(1);
}

const missingCopyright = out.filter(c => !c.copyright).map(c => c.name);
if (missingCopyright.length > 0) {
  console.error(
    `\n  go-attributions: licence found but no copyright line for:\n    ${missingCopyright.join('\n    ')}\n`,
  );
  process.exit(1);
}

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      _comment:
        'GENERATED by `npm run attributions:go`. The Go modules compiled into the transfer native ' +
        'archive (025). gen-attributions.mjs scans a Metro bundle and cannot see these. Committed so ' +
        'the drift check runs without Go installed.',
      modules: out,
    },
    null,
    2,
  )}\n`,
);
console.log(`go-attributions: ${out.length} Go modules ship inside the transfer archive.`);
